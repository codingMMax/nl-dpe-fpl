#!/usr/bin/env python3
"""checkEquivalence.py — the equivalence gate: the refactored simulator (v3/simulator/) against the frozen outputs of
the old one (frozen into work/equivalence/ref/ from git 816807b by the since-removed freezeReference.py).

  reports   every FC and attention build of the DSE, timing-only: cycles, every event line, every step (times and
            named events), counts, resources, basis; attention also ctrl.t_s and ctrl.done
  rows      the DSE rows' model columns: integers and strings exact, floats to 1e-9 relative
  corpus    the corpora regenerated by the ported case writers into work/equivalence/new/corpus/: the same files,
            every one byte-identical
A part whose new-side code is not built yet is reported as "not built" and does not fail the gate.
Usage: python3 v3/simulator/tests/checkEquivalence.py [--only reports,rows,corpus] [--ref DIR] [--jobs 8]
"""
from __future__ import annotations

import argparse
import csv
import filecmp
import gzip
import importlib
import json
import os
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

V3 = Path(__file__).resolve().parents[2]
REPO = V3.parent
sys.path.insert(0, str(V3))
from simulator.core.engine import run  # noqa: E402
from simulator.platform import area  # noqa: E402
from simulator.platform.platform import Platform  # noqa: E402

SNAP = V3 / "dse" / "fc_snapshot"
GENERATORS = {   # corpus name -> (generator, arguments), the same scripts the freeze ran (ported to the new package)
    "dimm_64x64": ("ip/dimm/gen_cases.py", ()),
    "softmax_64x64": ("ip/softmax/gen_cases.py", ("--preset", "corpus")),
    "softmax_bringup": ("ip/softmax/gen_cases.py", ("--preset", "bringup")),
    "softmax_rc": ("ip/softmax/gen_cases.py", ("--preset", "rc")),
    "acc_64x64": ("ip/softmax/acc_gen_cases.py", ("--preset", "corpus")),
    "acc_bringup": ("ip/softmax/acc_gen_cases.py", ("--preset", "bringup")),
    "head_64x64": ("top/gen_cases.py", ("--preset", "corpus")),
    "head_bringup": ("top/gen_cases.py", ("--preset", "bringup")),
}
COUNT_KEYS = dict(clb_add="clbAdd", clb_cmp="clbCompare", clb_sel="clbSelect", mem_rd_bytes="memReadBytes",
                  mem_wr_bytes="memWriteBytes", fifo_words="fifoWords")


def optional(module: str):
    """The new-side module, or None while it is not built."""
    try:
        return importlib.import_module(module)
    except ImportError:
        return None


def jsonable(x):
    if isinstance(x, dict):
        return {str(k): jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [jsonable(v) for v in x]
    if isinstance(x, np.ndarray):
        return x.tolist()
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, np.floating):
        return float(x)
    return x


def newReportDict(rep, extra: dict | None = None) -> dict:
    """The new Report in the frozen format (freezeReference.reportDict)."""
    out = dict(cycles=rep.cycles, events=rep.eventLines(),
               steps={inst: [dict(process=s.process, unit=s.unit, t_decide=s.tDecide, t_start=s.tStart,
                                  t_done=s.tDone, events=jsonable(s.events)) for s in steps]
                      for inst, steps in rep.steps.items()},
               counts={inst: dict(passes={f"{m}:{r}:{c}": n for (m, r, c), n in c_.passes.items()},
                                  **{old: getattr(c_, new) for old, new in COUNT_KEYS.items()})
                       for inst, c_ in rep.counts.items()},
               resources={inst: dict(crossbars={f"{m}:{r}:{c}": n for (m, r, c), n in r_.crossbars.items()},
                                     memories={f"{w}x{b}": n for (w, b), n in r_.memories.items()},
                                     mem_shared={f"{w}x{b}": n for (w, b), n in r_.memShared.items()})
                          for inst, r_ in rep.resources.items()},
               basis=dict(rep.basis))
    out.update(extra or {})
    return out


def diffReports(old: dict, new: dict) -> list:
    """The differences between two report dicts (empty = equal), each as one line."""
    out = []
    if old["cycles"] != new["cycles"]:
        out.append(f"cycles {old['cycles']} != {new['cycles']}")
    a, b = old["events"], new["events"]
    first = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), None)
    if first is None and len(a) != len(b):
        first = min(len(a), len(b))
    if first is not None:
        out.append(f"events: {len(a)} vs {len(b)} lines, first difference #{first}: "
                   f"old {a[first] if first < len(a) else None!r} | new {b[first] if first < len(b) else None!r}")
    for key in ("steps", "counts", "resources", "basis"):
        if sorted(old[key]) != sorted(new[key]):
            out.append(f"{key}: instances {sorted(old[key])} != {sorted(new[key])}")
            continue
        for inst in old[key]:
            x, y = old[key][inst], new[key][inst]
            if x != y:
                if key == "steps":
                    i = next((i for i, (s, t) in enumerate(zip(x, y)) if s != t), min(len(x), len(y)))
                    out.append(f"steps of {inst}: first difference at step #{i}: "
                               f"old {x[i] if i < len(x) else None} | new {y[i] if i < len(y) else None}")
                else:
                    out.append(f"{key} of {inst}: old {x} | new {y}")
    for key in set(old) - {"cycles", "events", "steps", "counts", "resources", "basis", "head_params"}:
        if old[key] != new.get(key):
            out.append(f"{key}: old {old[key]} | new {new.get(key)}")
    return out


def loadRef(path: Path) -> dict:
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return json.load(f)


# -- reports ----------------------------------------------------------------------------------------------------------
def checkFcReports(ref: Path, say) -> tuple:
    fcModule = optional("simulator.models.fc")
    files = sorted((ref / "reports").glob("fc_*.json.gz"))
    if fcModule is None:
        return "not built", 0
    bad = 0
    for f in files:
        old = loadRef(f)
        R, C, M, K, N = (int(x) for x in re.fullmatch(r"fc_(\d+)x(\d+)_(\d+)_(\d+)_(\d+)", f.name[:-8]).groups())
        g = fcModule.fc(K, N, R, C, M=M, platform=Platform("nl_dpe", rows=R, cols=C), passExtent=old["pass_extent"],
                        withValues=False)
        diff = diffReports(old, newReportDict(run(g), dict(pass_extent=old["pass_extent"])))
        if diff:
            bad += 1
            say(f"    FAIL {f.name}: " + "; ".join(diff[:3]))
    return ("ok" if not bad else f"{bad} differ"), len(files)


def checkAttentionReports(ref: Path, say) -> tuple:
    head = optional("simulator.models.attentionHead")
    files = sorted((ref / "reports").glob("att_*.json.gz"))
    if head is None:
        return "not built", 0
    bad = 0
    for f in files:
        old = loadRef(f)
        hp = old["head_params"]
        params = head.headParams(hp["NSEQ"], hp["DM"], hp["D"], hp["R"], hp["C"])
        g, parts = head.attentionHead(params, withValues=False)
        rep = run(g)
        ctrl = parts["ctrl"]
        new = newReportDict(rep, dict(ctrl_t_s=ctrl.tStart, ctrl_done=ctrl.done))
        diff = diffReports(old, new)
        if diff:
            bad += 1
            say(f"    FAIL {f.name}: " + "; ".join(diff[:3]))
    return ("ok" if not bad else f"{bad} differ"), len(files)


# -- rows -------------------------------------------------------------------------------------------------------------
def sameCell(a: str, b) -> bool:
    b = "" if b is None else str(b)
    if a == b:
        return True
    try:
        x, y = float(a), float(b)
    except ValueError:
        return False
    if a.lstrip("-").isdigit() or b.lstrip("-").isdigit():
        return x == y
    return abs(x - y) <= 1e-9 * max(1.0, abs(x))


def checkRows(ref: Path, say) -> dict:
    rows = optional("simulator.platform.rows")
    out = {}
    with open(ref / "rows" / "fc_rows.csv", newline="") as f:
        fcRef = list(csv.DictReader(f))
    if rows is None or not hasattr(rows, "fcRow"):
        out["fc"] = ("not built", len(fcRef))
    else:
        vtr = area.vtrTable(SNAP / "vtr_results.csv")
        bad = 0
        for r in fcRef:
            R, C = int(r["R"]), int(r["C"])
            got = rows.fcRow(R, C, (int(r["M"]), int(r["K"]), int(r["N"])), Platform("nl_dpe", rows=R, cols=C), vtr,
                             passExtent=r["pass_extent"])
            diff = [k for k in r if not sameCell(r[k], got.get(k))]
            if diff:
                bad += 1
                say(f"    FAIL fc row {r['config']} {r['M']}x{r['K']}x{r['N']}: columns {diff[:5]}")
        out["fc"] = (("ok" if not bad else f"{bad} differ"), len(fcRef))
    with open(ref / "rows" / "att_rows.csv", newline="") as f:
        attRef = list(csv.DictReader(f))
    if rows is None or not hasattr(rows, "attentionRow"):
        out["attention"] = ("not built", len(attRef))
    else:
        bad = 0
        for r in attRef:
            got = rows.attentionRow(r["shape"], int(r["n"]), int(r["d_model"]), int(r["d"]), int(r["R"]), int(r["C"]))
            diff = [k for k in r if not sameCell(r[k], got.get(k))]
            if diff:
                bad += 1
                say(f"    FAIL attention row {r['shape']} {r['config']}: columns {diff[:5]}")
        out["attention"] = (("ok" if not bad else f"{bad} differ"), len(attRef))
    return out


# -- corpora ----------------------------------------------------------------------------------------------------------
def ported(script: str) -> bool:
    """The generator's case writer imports the new package (grep of the writer it imports, or of itself)."""
    text = (V3 / script).read_text()
    m = re.search(r"^from (ip\.[\w.]+|top\.[\w.]+) import", text, re.M)
    writer = V3 / (m.group(1).replace(".", "/") + ".py") if m else V3 / script
    return "from simulator." in writer.read_text()


def regenerate(name: str, new: Path, logDir: Path) -> tuple:
    gen, args = GENERATORS[name]
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1", TMPDIR=str(V3 / "work" / "tmp"))
    with open(logDir / f"regen_{name}.log", "w") as log:
        rc = subprocess.run([sys.executable, str(V3 / gen), "--out", str(new / "corpus" / name), *args], cwd=REPO,
                            env=env, stdout=log, stderr=subprocess.STDOUT).returncode
    return name, rc


def sameFile(a: Path, b: Path) -> bool:
    """Byte-identical, except case.json, whose dictionaries may list their keys in another order."""
    if a.name == "case.json":
        return json.loads(a.read_text()) == json.loads(b.read_text())
    return filecmp.cmp(a, b, shallow=False)


def compareTrees(a: Path, b: Path) -> list:
    """Files that differ, are missing or extra, as 'what: path'."""
    fa = {str(p.relative_to(a)) for p in a.rglob("*") if p.is_file()}
    fb = {str(p.relative_to(b)) for p in b.rglob("*") if p.is_file()}
    out = [f"missing: {p}" for p in sorted(fa - fb)] + [f"extra: {p}" for p in sorted(fb - fa)]
    out += [f"differs: {p}" for p in sorted(fa & fb) if not sameFile(a / p, b / p)]
    return out


def checkCorpora(ref: Path, new: Path, logDir: Path, jobs: int, say) -> dict:
    out = {}
    todo = [n for n in GENERATORS if ported(GENERATORS[n][0])]
    for n in GENERATORS:
        if n not in todo:
            out[n] = ("not built", 0)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        results = list(pool.map(lambda n: regenerate(n, new, logDir), todo))
    for name, rc in results:
        nCases = len([x for x in (ref / "corpus" / name / "manifest.txt").read_text().split() if x])
        if rc:
            out[name] = (f"generator failed rc {rc} ({logDir / f'regen_{name}.log'})", nCases)
            continue
        diff = compareTrees(ref / "corpus" / name, new / "corpus" / name)
        if diff:
            say(f"    FAIL corpus {name}: {len(diff)} files: " + ", ".join(diff[:4]))
        out[name] = (("ok" if not diff else f"{len(diff)} files differ"), nCases)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--ref", default=str(V3 / "work" / "equivalence" / "ref"))
    ap.add_argument("--only", default="reports,rows,corpus")
    ap.add_argument("--jobs", type=int, default=8)
    a = ap.parse_args()
    ref, only = Path(a.ref), set(a.only.split(","))
    new = ref.parent / "new"
    logDir = ref.parent / "logs"
    new.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((ref / "manifest.json").read_text())
    lines = [f"equivalence: new simulator vs the reference frozen from git {manifest['commit'][:12]} ({manifest['generated']})"]

    def say(msg: str) -> None:
        print(msg, flush=True)
        lines.append(msg)
    t0 = time.time()
    results = {}                                              # part -> (verdict, n)
    if "reports" in only:
        results["reports: fc builds"] = checkFcReports(ref, say)
        results["reports: attention builds"] = checkAttentionReports(ref, say)
    if "rows" in only:
        for k, v in checkRows(ref, say).items():
            results[f"rows: {k}"] = v
    if "corpus" in only:
        for k, v in checkCorpora(ref, new, logDir, a.jobs, say).items():
            results[f"corpus: {k}"] = v
    failed = [k for k, (v, _) in results.items() if v not in ("ok", "not built")]
    for k, (v, n) in results.items():
        say(f"  {k:28s} {v:12s} {n:4d}")
    verdict = "ALL EQUAL (built parts)" if not failed else "DIFFERENCES: " + ", ".join(failed)
    say(f"equivalence: {verdict}  ({time.time() - t0:.0f}s)")
    (logDir / "equivalence_summary.txt").write_text("\n".join(lines) + "\n")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
